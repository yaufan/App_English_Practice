export type VocabItem = {
  id: string;
  en: string;
  zh: string;
  pos?: string;
  ex?: string;
  exZh?: string;
};

export type Deck = {
  id: string;
  title: string;
  subtitle: string;
  icon: string;
  items: VocabItem[];
};

type Raw = [en: string, zh: string, ex?: string, exZh?: string, pos?: string];

function build(deckId: string, rows: Raw[]): VocabItem[] {
  return rows.map(([en, zh, ex, exZh, pos]) => ({
    id: `${deckId}:${en.toLowerCase()}`,
    en,
    zh,
    ex,
    exZh,
    pos,
  }));
}

